"""The CLI command reference page, rendered from the Click command tree, the registry and OpenAPI.

Owns the Markdown of ``docs/users/cli-reference/commands.md``: an intro; the HTTP route of each
command's operation, the CLI-only commands and the HTTP-only operations, from ``registry`` and
the OpenAPI document; then one section per visible command in path order with its help, usage
line and a table of its arguments and options. The page depends only on how the commands and
routes are declared, never on the terminal width, color or environment, so
``make cli-reference`` rewrites it byte for byte and a test fails when it is stale. Hidden
commands, such as the legacy stubs, are left out. The OpenAPI document is an input, so this
package never imports the web framework that exports it.

Start from: render_reference.
"""

from __future__ import annotations

import html
import json
import re
import sys
from collections.abc import Iterator, Mapping, Sequence
from pathlib import Path

import click
import typer

from harborrag_app.cli.main import app
from harborrag_app.cli.registry import CLI_ONLY, COMMAND_OPERATIONS, HTTP_ONLY

_TITLE = "# CLI command reference"
_INTRO = (
    "Look up which HTTP operation each `harborrag` command calls, and the usage line, arguments "
    "and options of every command. How the CLI runs, its global options, output formats, errors "
    "and exit codes are in the [CLI reference](README.md)."
)
_GENERATED = (
    "This page is generated by `make cli-reference` from the CLI's own help, the command "
    "registry in `harborrag_app/cli/registry.py` and the OpenAPI export; to change it, change "
    "the command's help text or the registry."
)
_ROUTES_SECTION = (
    "## Commands and their HTTP routes\n\n"
    "Each command calls the operation behind its HTTP route, with the same input, output and "
    "error codes. `create` and `update` both call the route's `PUT`."
)
_CLI_ONLY_SECTION = (
    "## CLI-only commands\n\nThese commands have no HTTP route, because HTTP cannot do their job."
)
_HTTP_ONLY_SECTION = "## HTTP-only operations\n\nThese operations have no command."
_TABLE_HEADER = "| Name | Type | Default | Description |\n| --- | --- | --- | --- |"
_CODE_SPAN = re.compile(r"(`+[^`]*`+)")
_HTTP_METHODS = frozenset({"get", "put", "post", "patch", "delete"})
_USAGE = "usage: python -m harborrag_app.cli.reference OPENAPI_JSON\n"


def render_reference(openapi: Mapping[str, object]) -> str:
    """Render the command reference page.

    Args:
        openapi: The API's OpenAPI document, as ``make openapi`` exports it.

    Returns:
        Markdown ending in one newline: the intro, the route, CLI-only and HTTP-only tables,
        then a section per visible command.

    Raises:
        ValueError: An operation the registry names is not in ``openapi``.
    """
    routes = _routes(openapi)
    root = click.Context(typer.main.get_command(app), info_name="harborrag")
    sections = [_section(context) for context in _visible_commands(root)]
    tables = [_command_routes(routes), _cli_only(), _http_only(routes)]
    return "\n\n".join([_TITLE, _INTRO, _GENERATED, *tables, *sections]) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """Write the reference page to stdout, reading the OpenAPI document from the path given.

    Args:
        argv: ``[OPENAPI_JSON]``; ``None`` reads the process arguments.

    Returns:
        ``0``, or ``2`` when no single path is given.
    """
    args = sys.argv[1:] if argv is None else list(argv)
    if len(args) != 1:
        sys.stderr.write(_USAGE)
        return 2
    openapi = json.loads(Path(args[0]).read_text(encoding="utf-8"))
    sys.stdout.write(render_reference(openapi))
    return 0


def _routes(openapi: Mapping[str, object]) -> dict[str, str]:
    """``METHOD /path`` of each operationId in an OpenAPI document."""
    paths = openapi.get("paths")
    if not isinstance(paths, Mapping):
        raise ValueError("the OpenAPI document has no paths")
    routes: dict[str, str] = {}
    for path, path_item in paths.items():
        if not isinstance(path_item, Mapping):
            continue
        for method, operation in path_item.items():
            operation_id = operation.get("operationId") if isinstance(operation, Mapping) else None
            if method in _HTTP_METHODS and isinstance(operation_id, str):
                routes[operation_id] = f"{method.upper()} {path}"
    return routes


def _route(routes: Mapping[str, str], operation_id: str) -> str:
    """The route of ``operation_id``, which the registry names and OpenAPI must have."""
    try:
        return routes[operation_id]
    except KeyError:
        raise ValueError(f"operation {operation_id} is not in the OpenAPI document") from None


def _command_routes(routes: Mapping[str, str]) -> str:
    """The table of each command's operation and HTTP route, in command order."""
    rows = [
        _table_row(
            (_command_link(command), f"`{operation_id}`", f"`{_route(routes, operation_id)}`")
        )
        for command, operation_id in sorted(COMMAND_OPERATIONS.items())
    ]
    header = "| Command | Operation | HTTP route |\n| --- | --- | --- |"
    return "\n\n".join([_ROUTES_SECTION, "\n".join([header, *rows])])


def _cli_only() -> str:
    """The table of commands with no operation, with the reason."""
    rows = [
        _table_row((_command_link(command), _prose(reason)))
        for command, reason in sorted(CLI_ONLY.items())
    ]
    header = "| Command | Why it has no HTTP route |\n| --- | --- |"
    return "\n\n".join([_CLI_ONLY_SECTION, "\n".join([header, *rows])])


def _http_only(routes: Mapping[str, str]) -> str:
    """The table of operations with no command, with their route and the reason."""
    rows = [
        _table_row((f"`{operation_id}`", f"`{_route(routes, operation_id)}`", _prose(reason)))
        for operation_id, reason in sorted(HTTP_ONLY.items())
    ]
    header = "| Operation | HTTP route | Why it has no command |\n| --- | --- | --- |"
    return "\n\n".join([_HTTP_ONLY_SECTION, "\n".join([header, *rows])])


def _command_link(command: str) -> str:
    """A command path as code, linked to its section on this page."""
    path = f"harborrag {command}"
    return f"[`{path}`](#{path.replace(' ', '-')})"


def _table_row(cells: Sequence[str]) -> str:
    """One Markdown table row, with ``|`` inside a cell escaped."""
    return "| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |"


def _visible_commands(context: click.Context) -> Iterator[click.Context]:
    """Yield a context per visible runnable command under ``context``, in path order."""
    command = context.command
    if not isinstance(command, click.Group):
        yield context
        return
    for name in sorted(command.commands):
        subcommand = command.commands[name]
        if not subcommand.hidden:
            yield from _visible_commands(click.Context(subcommand, info_name=name, parent=context))


def _section(context: click.Context) -> str:
    """The ``##`` section of one command: its help, usage line and parameter table."""
    command = context.command
    usage = " ".join([context.command_path, *command.collect_usage_pieces(context)])
    blocks = [f"## {context.command_path}", *_paragraphs(command.help), f"```text\n{usage}\n```"]
    rows = [_row(param) for param in command.params if not getattr(param, "hidden", False)]
    if rows:
        blocks.append("\n".join([_TABLE_HEADER, *rows]))
    return "\n\n".join(blocks)


def _paragraphs(text: str | None) -> list[str]:
    """Help text as Markdown paragraphs, each on one line."""
    return [_prose(" ".join(part.split())) for part in (text or "").split("\n\n") if part.strip()]


def _row(param: click.Parameter) -> str:
    """One table row: name, type, default and help."""
    help_text = " ".join((getattr(param, "help", None) or "").split())
    return _table_row((_name(param), _type(param), _default(param), _prose(help_text)))


def _name(param: click.Parameter) -> str:
    """An option's flags and metavar, or an argument's metavar, as code."""
    if not isinstance(param, click.Option):
        return f"`{param.human_readable_name}`"
    flags = ", ".join([*param.opts, *param.secondary_opts])
    return f"`{flags} {param.metavar}`" if param.metavar else f"`{flags}`"


def _type(param: click.Parameter) -> str:
    """The choices of a choice parameter as code, else Click's name of the type."""
    if isinstance(param.type, click.Choice):
        return ", ".join(f"`{choice}`" for choice in param.type.choices)
    return param.type.name


def _default(param: click.Parameter) -> str:
    """``required``, the default as code, or nothing when there is none."""
    if param.required:
        return "required"
    default = param.default
    if default is None or default in ((), []):
        return ""
    if isinstance(default, bool):
        return f"`{str(default).lower()}`"
    return f"`{default}`"


def _prose(text: str) -> str:
    """``text`` with ``&``, ``<`` and ``>`` outside code spans as entities, so the page shows them."""
    return "".join(
        part if part.startswith("`") else html.escape(part, quote=False)
        for part in _CODE_SPAN.split(text)
    )


if __name__ == "__main__":
    raise SystemExit(main())
